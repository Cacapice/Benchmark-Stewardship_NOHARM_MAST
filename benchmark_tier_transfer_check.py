def recommend_next_step(available_data: Dict[str, bool]) -> Dict[str, object]:
    """Given what a team already has (a dict of the plain-English data
    requirements above, each mapped to True/False), return the lowest-tier
    statistic not yet unlocked -- i.e., the single highest-leverage next
    thing to build, and what's already usable today.

    `available_data` keys should match entries in each requirement's `needs`
    list (a simple string-containment check, not an exact-match registry --
    this is a planning aid, not a strict validator).
    """
    usable, blocked = [], []
    for name, req in STATISTIC_REQUIREMENTS.items():
        needs_met = all(
            any(have_key in need or need in have_key for have_key, have in available_data.items() if have)
            for need in req["needs"]
        )
        (usable if needs_met else blocked).append((name, req["tier"]))

    usable.sort(key=lambda nt: nt[1])
    blocked.sort(key=lambda nt: nt[1])

    return {
        "usable_today": [n for n, _ in usable],
        "recommended_next_to_unlock": blocked[0][0] if blocked else None,
        "blocked": [n for n, _ in blocked],
    }


