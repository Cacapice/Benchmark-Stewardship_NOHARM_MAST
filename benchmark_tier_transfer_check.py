@dataclass
class EvidenceProfile:
    """An interpretation of RELATIONSHIPS between surveillance statistics,
    not a combination of them into a score. Four rows, each a distinct
    observation of continued measurement fitness -- though NOT four
    independent ones: three are measurable with respect to the same scalar
    discrepancy series (see CHANNEL_INFORMATION_BASIS), and only rank
    stability resolves per-case identity. `concerning_channels` and
    `distinct_bases` expose that structure. `recommendation` is
    generated from the PATTERN across rows via suggest_next_investigation,
    not from any weighted sum. `refresh_policy` answers a DIFFERENT
    question from the same evidence -- see suggest_refresh_policy's
    docstring for the distinction.

    Each `*_direction` field is one of "up" / "down" / "flat" / "unknown" --
    "up" always means "further from the baseline / more concerning,"
    regardless of which row it's in, so the four rows can be read
    consistently at a glance.
    """
    model: str
    release: str
    cusum_direction: Direction
    transfer_discrepancy_direction: Direction
    rank_stability_direction: Direction
    adaptive_direction: Direction
    recommendation: str
    refresh_policy: str

    def __post_init__(self) -> None:
        """Enforce the formal evidence alphabet at construction time."""
        _validate_directions(
            self.cusum_direction,
            self.transfer_discrepancy_direction,
            self.rank_stability_direction,
            self.adaptive_direction,
        )

    @property
    def concerning_channels(self) -> List[str]:
        """Which rows read as concerning ('up', or 'down' for rank stability,
        where scrambling is the concerning direction)."""
        flags = [
            ("cusum", self.cusum_direction == "up"),
            ("transfer_discrepancy", self.transfer_discrepancy_direction == "up"),
            ("rank_stability", self.rank_stability_direction == "down"),
            ("adaptive", self.adaptive_direction == "up"),
        ]
        return [name for name, concerning in flags if concerning]

    @property
    def distinct_bases(self) -> int:
        """Number of distinct information sources the concerning rows draw
        on -- 0, 1, or 2. See `distinct_information_bases`."""
        return distinct_information_bases(self.concerning_channels)

    def render(self) -> str:
        """A compact, symbol-based summary -- the 'Evidence Profile' block
        the README shows, not a table of raw numbers.

        Rows are annotated with their information basis, and a concern count
        confined to a single basis is flagged as such: without that note a
        reader counts three agreeing rows and over-reads the concordance.
        """
        lines = [
            f"Evidence profile -- {self.model} @ {self.release}",
            f"  CUSUM                {_SYMBOLS[self.cusum_direction]}   [F_delta]",
            f"  Transfer discrepancy {_SYMBOLS[self.transfer_discrepancy_direction]}   [F_delta]",
            f"  Rank stability       {_SYMBOLS[self.rank_stability_direction]}   [F_case]",
            f"  Adaptive drift       {_SYMBOLS[self.adaptive_direction]}   [F_delta]",
        ]

        concerning = self.concerning_channels
        if len(concerning) >= 2 and self.distinct_bases == 1:
            basis = CHANNEL_INFORMATION_BASIS[concerning[0]]
            lines += [
                "",
                f"  Note: all {len(concerning)} concerning rows are {basis}-measurable --",
                "  statistics of the same underlying series, so their agreement is",
                "  weaker corroboration than the count suggests.",
            ]
        elif self.distinct_bases == 2:
            lines += [
                "",
                "  Note: concerning rows span both information bases -- the",
                "  discrepancy series and per-case identity agree independently.",
            ]

        lines += [
            "",
            f"  Investigation: {self.recommendation}",
            "",
            f"  Refresh policy: {self.refresh_policy}",
        ]
        return "\n".join(lines)


def build_evidence_profile(
    results: List[CaseResult],
    history: List[TierMeans],
    model: str,
    release: str,
    prior_release: Optional[str] = None,
    release_meta: Optional[Dict[str, ReleaseMeta]] = None,
    n_baseline: int = 12,
    k_sigma: float = 0.5,
    h_sigma: Optional[float] = None,
    rank_stable_threshold: float = 0.5,
    adaptive_r_threshold: float = 0.6,
    rank_use_interval: bool = False,
    rank_n_bootstrap: int = 1000,
    rank_seed: Optional[int] = None,
) -> EvidenceProfile:
    """Compute one EvidenceProfile from whatever inputs are available.
    Any row this module can't compute (insufficient history, no
    prior_release given, no release_meta given) is marked "unknown" rather
    than guessed -- an EvidenceProfile is honest about partial information,
    the same discipline as every other function in this module.

    `rank_use_interval` (default False, i.e. prior behaviour unchanged):

      By default the rank-stability row compares the BARE POINT ESTIMATE rho
      against `rank_stable_threshold`, with no reference to how much sampling
      noise that rho carries -- even though `core_case_rank_stability_ci`
      exists specifically to quantify it, and even though a core tier with a
      handful of shared cases can produce a rho well below threshold that is
      not distinguishable from a stable ordering at all. That is the same
      "single number with no sense of its own uncertainty" this module
      criticises elsewhere, applied to a row that feeds both
      `suggest_next_investigation` and `suggest_refresh_policy`.

      Setting this True routes the row through the BCa interval instead: the
      row reads "down" (scrambling) only when the interval's UPPER bound is
      still below `rank_stable_threshold` -- i.e. the data are inconsistent
      with a stable ordering, not merely compatible with instability. When
      the point estimate is below threshold but the interval straddles it,
      the row reads "unknown" rather than "flat", so the profile says "not
      resolvable at this sample size" instead of quietly asserting either
      answer.

      This is opt-in rather than the default because it changes the meaning
      of a row that downstream decision trees already consume; flipping it
      silently would alter existing deployments' recommendations without
      their operators knowing. It costs one bootstrap per profile.
    """
    # Row 1: CUSUM (Tier 0).
    cm = cusum_monitor(history, n_baseline=n_baseline, k_sigma=k_sigma, h_sigma=h_sigma)
    if not cm.get("computable", False):
        cusum_direction = "unknown"
    elif cm["alarmed"] and cm["first_alarm_direction"] == "increase":
        cusum_direction = "up"
    elif cm["alarmed"] and cm["first_alarm_direction"] == "decrease":
        cusum_direction = "down"
    else:
        cusum_direction = "flat"

    # Row 2: transfer discrepancy (Tier 0) -- drift_flag's z-score sign.
    df = drift_flag(history)
    if "z_score" not in df:
        transfer_direction = "unknown"
    elif df["flagged"] and df["z_score"] > 0:
        transfer_direction = "up"
    elif df["flagged"] and df["z_score"] < 0:
        transfer_direction = "down"
    else:
        transfer_direction = "flat"

    # Row 3: rank stability (Tier 2) -- needs a prior_release to compare against.
    if prior_release is None:
        rank_direction = "unknown"
    else:
        if rank_use_interval:
            rs = core_case_rank_stability_ci(
                results, model, prior_release, release,
                n_bootstrap=rank_n_bootstrap, seed=rank_seed, method="bca",
            )
        else:
            rs = core_case_rank_stability(results, model, prior_release, release)

        if not rs.get("computable", False):
            rank_direction = "unknown"
        elif not rank_use_interval:
            if rs["spearman_rho"] < rank_stable_threshold:
                rank_direction = "down"  # scrambling -- "down" = further from stable
            else:
                rank_direction = "flat"  # stable ranking -- nothing concerning to report
        elif not rs.get("bootstrap_computable", False):
            rank_direction = "unknown"
        elif rs["ci_high"] < rank_stable_threshold:
            # The whole interval sits below the stability threshold: the data
            # are inconsistent with a stable ordering, not merely compatible
            # with an unstable one.
            rank_direction = "down"
        elif rs["ci_low"] >= rank_stable_threshold:
            rank_direction = "flat"  # robustly stable
        else:
            # Interval straddles the threshold -- genuinely unresolved at this
            # sample size. Say so rather than asserting either answer.
            rank_direction = "unknown"

    # Row 4: adaptive drift (Tier 3) -- needs release_meta.
    if release_meta is None:
        adaptive_direction = "unknown"
    else:
        ao = adaptive_overfitting_check(history, release_meta)
        if not ao.get("computable", False):
            adaptive_direction = "unknown"
        elif ao["flagged"]:
            adaptive_direction = "up"
        else:
            adaptive_direction = "flat"

    recommendation = suggest_next_investigation(
        cusum_direction, transfer_direction, rank_direction, adaptive_direction
    )
    refresh_policy = suggest_refresh_policy(
        cusum_direction, transfer_direction, rank_direction, adaptive_direction
    )

    return EvidenceProfile(
        model=model,
        release=release,
        cusum_direction=cusum_direction,
        transfer_discrepancy_direction=transfer_direction,
        rank_stability_direction=rank_direction,
        adaptive_direction=adaptive_direction,
        recommendation=recommendation,
        refresh_policy=refresh_policy,
    )


@dataclass(frozen=True)
class GovernancePolicy:
    """Configurable lifecycle-routing tolerances.

    The default reproduces the published basis-aware decision tree exactly.
    Teams may supply a named policy without forking statistical code.
    """
    policy_id: str = "basis-aware-default-v1"
    require_distinct_bases_for_priority: bool = True
    minimum_concerning_channels_for_priority: int = 2
    minimum_concerning_channels_without_basis: int = 3
    prioritize_action: str = (
        "Evidence suggests meaningful drift across distinct information bases. "
        "Prioritize collection of additional prospective cases before the next release."
    )
    mixed_action: str = (
        "Evidence is mixed. Expand prospective sampling but retain the current core set."
    )
    stable_action: str = (
        "Evidence suggests the benchmark remains stable. Continue using the current benchmark."
    )


DEFAULT_GOVERNANCE_POLICY = GovernancePolicy()


def suggest_next_investigation(
    cusum_direction: Direction,
    transfer_discrepancy_direction: Direction,
    rank_stability_direction: Direction,
    adaptive_direction: Direction,
    *,
    policy: GovernancePolicy = DEFAULT_GOVERNANCE_POLICY,
) -> str:
    """A decision tree over evidence-profile directions, returning a
    SUGGESTED NEXT INVESTIGATION -- never a diagnosis. No branch below
    concludes "contamination" or "the benchmark is broken"; every branch
    names a place to look next, because that is the most this module's
    descriptive statistics can honestly support (see the module docstring's
    confound list -- at least five mechanisms besides contamination produce
    the same signatures this tree branches on).

    Deliberately does NOT gate on CUSUM alone: a mean-based statistic can be
    silent while rank stability collapses (exactly the r4->r5 case the
    bundled demo constructs), and that discordance is itself informative,
    not something the tree should be blind to just because the mean-based
    row looks quiet.
    """
    rows = _validate_directions(
        cusum_direction,
        transfer_discrepancy_direction,
        rank_stability_direction,
        adaptive_direction,
    )
    cusum_direction, transfer_discrepancy_direction, rank_stability_direction, adaptive_direction = rows
    if all(d == "unknown" for d in rows):
        return "Insufficient data across every row -- continue accumulating releases and metadata before drawing any conclusion."

    mean_based_concern = cusum_direction in ("up", "down") or transfer_discrepancy_direction in ("up", "down")
    rank_concern = rank_stability_direction == "down"
    adaptive_concern = adaptive_direction == "up"

    if not mean_based_concern and not rank_concern and not adaptive_concern:
        return "No persistent change detected in any row -- continue monitoring; no investigation indicated yet."

    if not mean_based_concern and rank_concern:
        base = (
            "Mean-based statistics (CUSUM, transfer discrepancy) show no persistent "
            "shift, but case-level rank stability has collapsed -- a discordance "
            "mean-based measures alone would miss. Investigate case-level "
            "composition directly."
        )
    elif mean_based_concern and rank_concern:
        base = (
            "Persistent change detected, alongside a scrambled case-level ordering "
            "-- investigate case-level composition or ordering changes, not just "
            "the aggregate trend."
        )
    elif mean_based_concern and rank_stability_direction == "unknown":
        base = (
            "Persistent change detected. Rank stability not computable (no "
            "prior_release given) -- add it to distinguish a case-mix shift from "
            "a scrambled ordering."
        )
    elif mean_based_concern:
        base = (
            "Persistent change detected, with a stable case-level ordering -- "
            "investigate distributional or case-mix shift (the ordering itself "
            "looks intact)."
        )
    else:
        # Only the adaptive row shows concern; mean-based and rank are both quiet.
        base = (
            "No persistent mean-level or rank-level shift detected, but the "
            "adaptive-drift correlation alone is elevated -- worth continued "
            "monitoring even though other rows are quiet."
        )

    if adaptive_direction == "unknown":
        tail = (
            " Adaptive-drift correlation not computable (no release_meta given) "
            "-- add submission counts to rule adaptive optimization in or out."
        )
    elif adaptive_concern and "adaptive-drift correlation alone is elevated" not in base:
        tail = (
            " Adaptive-drift correlation is also elevated -- adaptive optimization "
            "against repeated feedback cannot be ruled out; review submission "
            "history."
        )
    elif adaptive_direction == "flat":
        tail = (
            " No evidence of adaptive optimization from submission counts -- a "
            "distributional or content change is more likely than adaptive tuning."
        )
    else:
        tail = ""

    return base + tail


def suggest_refresh_policy(
    cusum_direction: Direction,
    transfer_discrepancy_direction: Direction,
    rank_stability_direction: Direction,
    adaptive_direction: Direction,
    basis_aware: bool = True,
    *,
    policy: GovernancePolicy = DEFAULT_GOVERNANCE_POLICY,
) -> str:
    """Recommend a benchmark lifecycle action.

    When basis_aware=True (default), agreement across distinct information
    bases is required for the strongest 'prioritize new cases' action,
    preventing the triple-weighting of the F_delta gap series.
    """
    rows = _validate_directions(
        cusum_direction,
        transfer_discrepancy_direction,
        rank_stability_direction,
        adaptive_direction,
    )
    cusum_direction, transfer_discrepancy_direction, rank_stability_direction, adaptive_direction = rows

    if all(d == "unknown" for d in rows):
        return (
            "Insufficient evidence to inform refresh policy -- continue "
            "accumulating releases and metadata before deciding anything "
            "about the benchmark's lifecycle."
        )

    concerning = [d for d in rows if d in ("up", "down")]

    if not concerning:
        return policy.stable_action

    if not basis_aware:
        if len(concerning) >= policy.minimum_concerning_channels_without_basis:
            return policy.prioritize_action
        return policy.mixed_action

    if not policy.require_distinct_bases_for_priority:
        if len(concerning) >= policy.minimum_concerning_channels_for_priority:
            return policy.prioritize_action
        return policy.mixed_action

    delta_concerning = sum(
        1 for d in [cusum_direction, transfer_discrepancy_direction, adaptive_direction]
        if d in ("up", "down")
    )
    case_concerning = 1 if rank_stability_direction in ("up", "down") else 0
    distinct_bases_triggered = (1 if delta_concerning > 0 else 0) + case_concerning

    if (
        distinct_bases_triggered == 2
        and len(concerning) >= policy.minimum_concerning_channels_for_priority
    ):
        return policy.prioritize_action

    return policy.mixed_action

