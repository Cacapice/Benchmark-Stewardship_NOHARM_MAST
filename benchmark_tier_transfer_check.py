"""
Benchmark Measurement Surveillance -- reference implementation.

Monitors whether a benchmark continues to produce evidence that transfers
to deployment performance, release over release, rather than assuming that
relationship persists once established at design time. This module is the
code. Why this exists: README.md. The theory, design rationale, and
worked examples: DESIGN_PAPER.md. Read those first if you want the
"why"; this docstring covers "what to call," and together with
STATISTIC_REQUIREMENTS and recommend_next_step(...) it is the
integration reference.

Quick orientation
--------------------
- Start here: `BenchmarkMonitor` -- call `.update(case_results, release)`
  once per release; wraps `cusum_monitor`, the recommended default check,
  and requires no k_sigma/h_sigma/n_baseline decisions.
- Four evidence sources, unlocked by data cost (Tiers 0-3, see
  `STATISTIC_REQUIREMENTS` / `recommend_next_step`): `cusum_monitor` /
  `drift_flag` (Tier 0), `compute_tier_means` / `probability_discrepancy_
  increased` (Tier 1), `core_case_rank_stability`(_ci) (Tier 2),
  `pre_post_release_gap` / `adaptive_overfitting_check`/`_regression`
  (Tier 3), `benjamini_hochberg` (Tier 4).
- `build_evidence_profile` synthesizes whatever of the above is available
  into an `EvidenceProfile` -- never a composite score.
  `suggest_next_investigation` (where to look) and `suggest_refresh_policy`
  (what to do about the benchmark's lifecycle) turn that into two
  different recommendations, neither a diagnosis.

The data contract
--------------------
Everything operates on one record type:

    CaseResult(model, release, tier, case_id, score)

`tier` is "core" | "rolling" | "prospective". `case_id` must be STABLE
across releases for the core tier specifically (fixed case set); rolling
and prospective case_ids only need to be unique within a release. Getting
this wrong silently zeroes out rank-stability checks rather than erroring
loudly -- get it right at ingestion time. See "The data-collection
tiers" in DESIGN_PAPER.md for the full walkthrough.

What this does NOT do
------------------------
- Not a diagnosis: an alarm means "investigate," never "contaminated" --
  at least five non-contamination mechanisms produce the same signature
  (case-mix shift, distribution shift, rubric change, measurement-
  uncertainty drift, genuine model specialization).
- Not a composite score: statistics are preserved side by side in
  `EvidenceProfile`, never weighted or summed into one number.
- Not a certified transfer-guarantee bound: nothing here is a computed
  `omega_D` in the Inferential Fidelity Framework's sense (see
  DESIGN_PAPER.md's "Relationship to the Inferential Fidelity Framework").
- Not a statistically estimated latent variable: "continued benchmark
  measurement fitness" -- deliberately not "validity" or "reliability",
  which carry narrower, specific meanings in psychometrics this module
  doesn't address -- is a conceptual organizing idea, not something any
  function here fits a Bayesian/state-space/factor-analytic model to.

Status: SYNTHETIC DEMONSTRATION DATA ONLY. No real NOHARM/MAST per-case,
per-tier scores are used anywhere below -- ARISE has not released tiered
case-level data, and none is fabricated here. `_synthetic_scenario()` and
its companions exist only to show the module producing correct, readable
output; every number in them is invented and labeled as such.
"""
