def _synthetic_scenario() -> List[CaseResult]:
    """A single synthetic model ('demo-model') across five invented releases.
    Core rises fastest (a fixed, familiar set -- easiest to optimize against).
    Rolling rises more modestly (updated periodically, harder to overfit to).
    Prospective plateaus (genuinely unseen cases each release). Every number
    here is fabricated for illustration only.

    Core case_ids are release-INDEPENDENT (case_0 .. case_19), since the core
    tier is fixed by design -- this is also what core_case_rank_stability
    needs to have shared cases to correlate across releases. Per-case
    offsets are symmetric around zero (-0.05 .. +0.05), so permuting which
    case gets which offset leaves the release MEAN exactly unchanged while
    changing which specific cases are "hard" or "easy" -- releases r1-r4 use
    the same offset-to-case mapping (stable ranking, rho = 1.0 pairwise), and
    r5 uses the reversed mapping (scrambled ranking, rho = -1.0 vs r4) to
    demonstrate a scenario the mean and drift_flag cannot see on their own.
    """
    releases = ["r1", "r2", "r3", "r4", "r5"]
    core_scores        = [0.70, 0.74, 0.78, 0.83, 0.88]  # invented
    rolling_scores     = [0.70, 0.72, 0.75, 0.78, 0.81]  # invented
    prospective_scores = [0.69, 0.70, 0.71, 0.72, 0.73]  # invented

    n_core_cases = 20
    offsets = [-0.05 + 0.10 * i / (n_core_cases - 1) for i in range(n_core_cases)]  # symmetric, sum ~ 0

    results: List[CaseResult] = []
    for rel, core, rolling, prosp in zip(releases, core_scores, rolling_scores, prospective_scores):
        for i in range(n_core_cases):
            offset = offsets[n_core_cases - 1 - i] if rel == "r5" else offsets[i]  # reversed mapping at r5
            results.append(CaseResult("demo-model", rel, "core", f"case_{i}", core + offset))
        for i in range(20):
            results.append(CaseResult("demo-model", rel, "rolling", f"roll_{rel}_{i}", rolling))
        for i in range(20):
            results.append(CaseResult("demo-model", rel, "prospective", f"pros_{rel}_{i}", prosp))
    return results


