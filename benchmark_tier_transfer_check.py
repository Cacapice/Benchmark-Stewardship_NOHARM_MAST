# ---------------------------------------------------------------------------
# INFORMATION BASIS OF THE EVIDENCE CHANNELS
#
# The four Evidence Profile rows are NOT four independent observations, and
# earlier versions of this module described them that way. They are four
# statistics computed over two distinct information sources:
#
#   F_delta -- the sigma-algebra generated by the scalar discrepancy series
#              {Delta_t} together with release metadata. `cusum_monitor`,
#              `drift_flag`, and `adaptive_overfitting_check` all default to
#              gap_core_prospective and read only from `history`/`release_meta`,
#              so all three are F_delta-measurable.
#
#   F_case  -- additionally resolves per-case identity within the core tier.
#              `core_case_rank_stability` is the only channel that reads it.
#
# The distinction is testable, not rhetorical. Permuting core scores WITHIN
# each release preserves every tier mean exactly, so {Delta_t} is unchanged
# bit for bit; rows measurable w.r.t. F_delta cannot move, while rank
# stability can go from "flat" to "down". See
# `test_permutation_within_release_moves_only_the_rank_row`.
#
# Consequence, stated plainly because it qualifies this module's own central
# principle: concordance among F_delta-measurable rows is substantially
# weaker evidence than four-way concordance would be, because those rows are
# three views of one scalar sequence and tend to move together under any real
# movement in Delta_t. `suggest_refresh_policy`'s concern count weights all
# four rows equally, which therefore triple-weights F_delta and single-weights
# F_case. `distinct_information_bases` exists so that fact is legible at the
# point of use rather than buried here.
# ---------------------------------------------------------------------------

InformationBasis = Literal["F_delta", "F_case"]

CHANNEL_INFORMATION_BASIS: Dict[str, InformationBasis] = {
    "cusum": "F_delta",
    "transfer_discrepancy": "F_delta",
    "rank_stability": "F_case",
    "adaptive": "F_delta",
}


def distinct_information_bases(concerning_channels: List[str]) -> int:
    """How many DISTINCT information sources a set of concerning rows draws
    on -- at most 2, given `CHANNEL_INFORMATION_BASIS`.

    Use this to qualify a concern count. Three concerning rows drawn from a
    single basis are three statistics of the same scalar series agreeing with
    each other, which is close to structurally expected; two concerning rows
    spanning both bases are genuinely corroborating observations. The raw
    count cannot tell those apart, and the second is the stronger evidence
    despite the smaller number.
    """
    return len({CHANNEL_INFORMATION_BASIS[c] for c in concerning_channels})


def _validate_direction(value: str, field_name: str) -> Direction:
    """Validate one Evidence Profile direction at the public API boundary."""
    if value not in VALID_DIRECTIONS:
        allowed = ", ".join(repr(item) for item in VALID_DIRECTIONS)
        raise ValueError(
            f"{field_name} must be one of {allowed}; got {value!r}"
        )
    return cast(Direction, value)


def _validate_directions(
    cusum_direction: str,
    transfer_discrepancy_direction: str,
    rank_stability_direction: str,
    adaptive_direction: str,
) -> Tuple[Direction, Direction, Direction, Direction]:
    """Validate and normalize the four-coordinate evidence domain."""
    return (
        _validate_direction(cusum_direction, "cusum_direction"),
        _validate_direction(
            transfer_discrepancy_direction,
            "transfer_discrepancy_direction",
        ),
        _validate_direction(rank_stability_direction, "rank_stability_direction"),
        _validate_direction(adaptive_direction, "adaptive_direction"),
    )


@dataclass(frozen=True)
class CaseResult:
    model: str
    release: str
    tier: str
    case_id: str
    score: float

    def __post_init__(self):
        if self.tier not in VALID_TIERS:
            raise ValueError(f"tier must be one of {VALID_TIERS}, got {self.tier!r}")


@dataclass
class TierMeans:
    model: str
    release: str
    core_mean: Optional[float]
    rolling_mean: Optional[float]
    prospective_mean: Optional[float]
    core_std: Optional[float]
    rolling_std: Optional[float]
    prospective_std: Optional[float]
    n_core: int
    n_rolling: int
    n_prospective: int

    def _gap(self, a: Optional[float], b: Optional[float]) -> Optional[float]:
        if a is None or b is None:
            return None
        return a - b

    @property
    def gap_core_rolling(self) -> Optional[float]:
        """core_mean - rolling_mean. Reflects benchmark aging: how much a
        fixed core diverges from a currently-updated case mix."""
        return self._gap(self.core_mean, self.rolling_mean)

    @property
    def gap_core_prospective(self) -> Optional[float]:
        """core_mean - prospective_mean. The primary transfer discrepancy
        statistic (Delta_t): the gap between the tier being tracked/optimized
        against and cases the model could not have seen -- one observation
        of continued measurement fitness at this release, not a
        deployment-readiness signal on its own. Deployment readiness
        also depends on calibration, subgroup performance, and robustness
        this module does not measure."""
        return self._gap(self.core_mean, self.prospective_mean)

    @property
    def gap_rolling_prospective(self) -> Optional[float]:
        """rolling_mean - prospective_mean. Isolates whether a *currently
        updated* benchmark still transfers to prospective cases, separating
        "stale core" concerns from genuine generalization failure."""
        return self._gap(self.rolling_mean, self.prospective_mean)


def compute_tier_means(results: List[CaseResult], model: str, release: str) -> TierMeans:
    """Compute per-tier means, standard deviations, and case counts for one
    model at one release.

    The standard deviations exist to catch what the means alone cannot: a
    scenario where hard cases within a tier get worse and easy cases get
    better by a matching amount, leaving the mean (and therefore every gap
    computed from it) unchanged while something real has shifted underneath.
    A rising `*_std` alongside a flat `gap_core_prospective` is that
    scenario's signature.
    """
    subset = [r for r in results if r.model == model and r.release == release]
    by_tier = {t: [r.score for r in subset if r.tier == t] for t in VALID_TIERS}

    def _std(scores: List[float]) -> Optional[float]:
        return stdev(scores) if len(scores) >= 2 else None

    return TierMeans(
        model=model,
        release=release,
        core_mean=mean(by_tier["core"]) if by_tier["core"] else None,
        rolling_mean=mean(by_tier["rolling"]) if by_tier["rolling"] else None,
        prospective_mean=mean(by_tier["prospective"]) if by_tier["prospective"] else None,
        core_std=_std(by_tier["core"]),
        rolling_std=_std(by_tier["rolling"]),
        prospective_std=_std(by_tier["prospective"]),
        n_core=len(by_tier["core"]),
        n_rolling=len(by_tier["rolling"]),
        n_prospective=len(by_tier["prospective"]),
    )


def drift_flag(
    history: List[TierMeans],
    gap_name: str = "gap_core_prospective",
    z_threshold: float = 1.5,
) -> Dict[str, object]:
    """Flag whether the most recent gap (default: core-vs-prospective, the
    transfer discrepancy statistic) is an outlier relative to this model's
    own prior gap history.

    Deliberately the simplest possible check: a z-score of the latest gap
    against the mean/stdev of the same model's prior gaps. Answers "has this
    widened relative to this model's own history?" -- not "is this gap large
    in absolute terms?" -- since different clinical domains may have
    different baseline gaps for reasons unrelated to benchmark optimization
    (case difficulty distribution, annotation protocol differences, etc).

    Requires at least 4 releases with a computable gap before flagging;
    returns flagged=False with a reason otherwise, rather than a false
    negative dressed up as a stable answer.
    """
    valid = [g for g in history if getattr(g, gap_name) is not None]
    if len(valid) < 4:
        return {"flagged": False, "reason": f"insufficient release history for {gap_name} (need >= 4)"}

    *prior, latest = valid
    prior_gaps = [getattr(g, gap_name) for g in prior]
    latest_gap = getattr(latest, gap_name)
    mu, sigma = mean(prior_gaps), stdev(prior_gaps)
    if sigma == 0:
        z = float("inf") if latest_gap != mu else 0.0
    else:
        z = (latest_gap - mu) / sigma

    return {
        "flagged": z >= z_threshold,
        "gap_name": gap_name,
        "z_score": z,
        "latest_gap": latest_gap,
        "prior_mean_gap": mu,
        "prior_stdev_gap": sigma,
        "n_prior_releases": len(prior),
    }


@dataclass(frozen=True)
class ReleaseMeta:
    """Bookkeeping about one release, supplied by the caller -- not derived
    from CaseResult, since neither a calendar date nor a submission count is
    per-case information.

    release            -- must match the `release` label used in CaseResult
    date                -- calendar date this release was evaluated
    n_prior_submissions -- cumulative number of times this developer had
                            already submitted a model/prompt variant to this
                            tier's evaluator, BEFORE this release. This is
                            the quantity the adaptive-overfitting channel
                            (below) is tracked against -- not release order,
                            not calendar time, but query count.
    """
    release: str
    date: date
    n_prior_submissions: int


def pre_post_release_gap(
    history: List[TierMeans],
    release_meta: Dict[str, ReleaseMeta],
    public_release_date: date,
    gap_name: str = "gap_core_prospective",
) -> Dict[str, object]:
    """Channel 1 (direct memorization): split a model's release history into
    before/after a tier's public-release date and compare mean gap.

    A gap that jumps specifically at (or soon after) `public_release_date` --
    rather than drifting smoothly across the whole history -- is evidence
    consistent with direct memorization of newly-public cases, distinct from
    the gradual, submission-count-linked pattern channel 2 looks for.
    """
    pre, post = [], []
    for h in history:
        meta = release_meta.get(h.release)
        gap = getattr(h, gap_name)
        if meta is None or gap is None:
            continue
        (pre if meta.date < public_release_date else post).append(gap)

    if not pre or not post:
        return {
            "computable": False,
            "reason": "need at least one release on each side of the public-release date",
            "n_pre": len(pre),
            "n_post": len(post),
        }

    return {
        "computable": True,
        "gap_name": gap_name,
        "mean_gap_pre_release": mean(pre),
        "mean_gap_post_release": mean(post),
        "delta": mean(post) - mean(pre),
        "n_pre": len(pre),
        "n_post": len(post),
    }


def _pearson_r(xs: List[float], ys: List[float]) -> Optional[float]:
    n = len(xs)
    if n < 2:
        return None
    mx, my = mean(xs), mean(ys)
    num = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    denom_x = sum((x - mx) ** 2 for x in xs) ** 0.5
    denom_y = sum((y - my) ** 2 for y in ys) ** 0.5
    if denom_x == 0 or denom_y == 0:
        return None
    return num / (denom_x * denom_y)


def adaptive_overfitting_check(
    history: List[TierMeans],
    release_meta: Dict[str, ReleaseMeta],
    gap_name: str = "gap_core_prospective",
    r_threshold: float = 0.6,
) -> Dict[str, object]:
    """Channel 2 (indirect / adaptive drift, no data ever revealed): test
    whether the gap correlates with CUMULATIVE SUBMISSION COUNT rather than
    with release order or calendar time.

    Rationale: a developer who never sees a single case can still overfit the
    evaluator itself through repeated adaptive queries -- the reusable-holdout
    problem (Dwork et al. 2015). The tell-tale signature is a gap that grows
    specifically with how many times this developer has queried the
    evaluator, not merely with how much time has passed or how many releases
    have shipped. This function reports a simple Pearson correlation between
    `n_prior_submissions` and the gap; it does not attempt to control for
    confounds (e.g. genuinely improving models also submit more often), so a
    positive correlation is a prompt for scrutiny, not proof of adaptive
    overfitting on its own.
    """
    xs, ys = [], []
    for h in history:
        meta = release_meta.get(h.release)
        gap = getattr(h, gap_name)
        if meta is None or gap is None:
            continue
        xs.append(meta.n_prior_submissions)
        ys.append(gap)

    if len(xs) < 4:
        return {"computable": False, "reason": "need >= 4 releases with metadata and a computable gap"}

    r = _pearson_r(xs, ys)
    if r is None:
        return {"computable": False, "reason": "degenerate input (zero variance in submissions or gap)"}

    return {
        "computable": True,
        "gap_name": gap_name,
        "pearson_r_submissions_vs_gap": r,
        "flagged": r >= r_threshold,
        "n_releases": len(xs),
        "note": (
            "Correlation only -- consistent with, not proof of, adaptive "
            "overfitting to repeated evaluator feedback. Distinguish from "
            "genuine improvement by comparing against prospective performance "
            "specifically, and by checking whether submission count predicts "
            "the gap even after controlling for release order."
        ),
    }


def _phi(z: float) -> float:
    """Standard normal CDF, via math.erfc (standard library -- no scipy)."""
    return 0.5 * math.erfc(-z / math.sqrt(2))


def _phi_inv(p: float) -> Optional[float]:
    """Inverse standard normal CDF (probit).

    Uses scipy.stats.norm.ppf if available for maximum numerical accuracy;
    falls back to Acklam's rational approximation otherwise.
    """
    if not (0.0 < p < 1.0):
        return None

    if _HAS_SCIPY:
        return float(_scipy_norm.ppf(p))

    # --- Fallback: Acklam's rational approximation ---
    a = [-3.969683028665376e+01, 2.209460984245205e+02, -2.759285104469687e+02,
         1.383577518672690e+02, -3.066479806614716e+01, 2.506628277459239e+00]
    b = [-5.447609879822406e+01, 1.615858368580409e+02, -1.556989798598866e+02,
         6.680131188771972e+01, -1.328068155288572e+01]
    c = [-7.784894002430293e-03, -3.223964580411365e-01, -2.400758277161838e+00,
         -2.549732539343734e+00, 4.374664141464968e+00, 2.938163982698783e+00]
    d = [7.784695709041468e-03, 3.224671290700398e-01, 2.445134137142996e+00,
         3.754408661907416e+00]
    p_low = 0.02425
    if p < p_low:
        q = math.sqrt(-2.0 * math.log(p))
        return (((((c[0]*q + c[1])*q + c[2])*q + c[3])*q + c[4])*q + c[5]) / \
               ((((d[0]*q + d[1])*q + d[2])*q + d[3])*q + 1.0)
    if p <= 1.0 - p_low:
        q = p - 0.5
        r = q * q
        return (((((a[0]*r + a[1])*r + a[2])*r + a[3])*r + a[4])*r + a[5]) * q / \
               (((((b[0]*r + b[1])*r + b[2])*r + b[3])*r + b[4])*r + 1.0)
    q = math.sqrt(-2.0 * math.log(1.0 - p))
    return -(((((c[0]*q + c[1])*q + c[2])*q + c[3])*q + c[4])*q + c[5]) / \
            ((((d[0]*q + d[1])*q + d[2])*q + d[3])*q + 1.0)

def _sorted_quantile(sorted_values: List[float], p: float) -> float:
    """Index-based quantile of an ALREADY-SORTED list, using the same
    convention as the original percentile intervals in this module so that
    `method="percentile"` reproduces prior behaviour exactly."""
    idx = int(p * len(sorted_values))
    return sorted_values[min(len(sorted_values) - 1, max(0, idx))]


def _bca_bounds(
    boot_values: List[float],
    point_estimate: float,
    jackknife_values: List[float],
    alpha: float = 0.05,
) -> Dict[str, object]:
    """Bias-corrected and accelerated (BCa) bootstrap interval bounds.

    Why this rather than the plain percentile interval: the percentile
    bootstrap assumes the bootstrap distribution is centred on the point
    estimate and symmetric enough that the naive 2.5%/97.5% cut points are
    the right ones. For a BOUNDED statistic estimated from FEW observations
    -- exactly Spearman's rho on a handful of shared core cases -- neither
    holds. As rho approaches +1 the sampling distribution is compressed
    against the boundary and skewed, so the naive cut points are simply the
    wrong ones.

    NOTE ON DIRECTION: the correction is NOT reliably one-directional, and
    should not be described as "tightening" the interval. Its sign follows
    z0, which is a property of the data. Both directions occur in this
    module's own test suite, on realistic core-tier data:

      - where the bootstrap median sits BELOW the point estimate, BCa raises
        the lower bound (a stable core set stops looking unstable);
      - where it sits ABOVE, BCa lowers it -- and this is the more
        consequential case, because it can turn an interval that excluded
        zero into one that includes it, i.e. it withdraws a "robust finding"
        that was an artefact of the naive cut points.

    Do not reach for this expecting narrower intervals. Reach for it because
    the naive endpoints are miscalibrated in an unknown direction, and this
    estimates which.

    BCa corrects two distinct things:

      z0 (bias correction) -- how far the bootstrap distribution's MEDIAN
          sits from the point estimate, in normal-quantile units;
          z0 = Phi^-1( #{theta*_b < theta_hat} / B ).
      a  (acceleration)    -- how fast the standard error changes with the
          parameter value (skewness), estimated by jackknife:
          a = sum(d_i^3) / (6 * (sum(d_i^2))^1.5), d_i = mean(jack) - jack_i.

    The adjusted cut points are then
        alpha_lo = Phi( z0 + (z0 + z_alpha)   / (1 - a*(z0 + z_alpha)) )
        alpha_hi = Phi( z0 + (z0 + z_1-alpha) / (1 - a*(z0 + z_1-alpha)) )
    and the interval is read off the SAME bootstrap replicates at those
    adjusted quantiles -- no new resampling, so this costs one jackknife
    pass (n extra statistic evaluations) and nothing else.

    IMPORTANT -- the cheap alternative that does NOT work: Fisher
    z-transforming (arctanh) the replicates before taking percentiles is a
    no-op. The percentile bootstrap is invariant under any monotone
    transformation, so transform-then-percentile-then-back returns bit-for-bit
    the same interval. BCa is transformation-respecting in the same way but
    additionally fixes median-bias and skew, which is why it is the actual
    upgrade rather than the appearance of one.

    Returns a dict with `computable`, and when computable: `ci_low`,
    `ci_high`, `z0`, `acceleration`, `alpha_lo`, `alpha_hi`. When the
    correction is undefined (all replicates on one side of the point
    estimate, degenerate jackknife, or an unstable denominator) it returns
    `computable: False` with a `reason` so the caller can fall back to the
    percentile interval EXPLICITLY rather than silently.
    """
    b = len(boot_values)
    if b < 2:
        return {"computable": False, "reason": "need >= 2 bootstrap replicates"}

    ordered = sorted(boot_values)

    n_below = sum(1 for v in boot_values if v < point_estimate)
    z0 = _phi_inv(n_below / b)
    if z0 is None:
        return {
            "computable": False,
            "reason": (
                "bias correction undefined -- every bootstrap replicate fell on "
                "one side of the point estimate (usually a boundary case, e.g. "
                "rho = +/-1, or too few distinct values to resample)"
            ),
        }

    if len(jackknife_values) < 2:
        return {"computable": False, "reason": "need >= 2 jackknife values for the acceleration term"}

    jack_mean = mean(jackknife_values)
    diffs = [jack_mean - t for t in jackknife_values]
    denom = 6.0 * (sum(d ** 2 for d in diffs) ** 1.5)
    if denom == 0:
        acceleration = 0.0  # zero jackknife variance -> no skewness correction available
    else:
        acceleration = sum(d ** 3 for d in diffs) / denom

    z_alpha = _phi_inv(alpha / 2.0)
    z_one_minus = _phi_inv(1.0 - alpha / 2.0)
    if z_alpha is None or z_one_minus is None:
        return {"computable": False, "reason": "invalid alpha"}

    def _adjust(z_q: float) -> Optional[float]:
        inner = z0 + z_q
        denominator = 1.0 - acceleration * inner
        if denominator <= 0:
            return None  # acceleration too large for this quantile -- interval undefined
        return _phi(z0 + inner / denominator)

    alpha_lo = _adjust(z_alpha)
    alpha_hi = _adjust(z_one_minus)
    if alpha_lo is None or alpha_hi is None or not (0.0 < alpha_lo < alpha_hi < 1.0):
        return {
            "computable": False,
            "reason": "adjusted quantiles out of range -- acceleration term too extreme at this sample size",
        }

    return {
        "computable": True,
        "ci_low": _sorted_quantile(ordered, alpha_lo),
        "ci_high": _sorted_quantile(ordered, alpha_hi),
        "z0": z0,
        "acceleration": acceleration,
        "alpha_lo": alpha_lo,
        "alpha_hi": alpha_hi,
    }


def _rank(values: List[float]) -> List[float]:
    """Average ranks (1-indexed), handling ties by averaging -- the standard
    convention for Spearman's rho."""
    order = sorted(range(len(values)), key=lambda i: values[i])
    ranks = [0.0] * len(values)
    i = 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and values[order[j + 1]] == values[order[i]]:
            j += 1
        avg_rank = (i + j) / 2 + 1  # average of the tied 1-indexed positions
        for k in range(i, j + 1):
            ranks[order[k]] = avg_rank
        i = j + 1
    return ranks


def core_case_rank_stability(
    results: List[CaseResult],
    model: str,
    release_a: str,
    release_b: str,
) -> Dict[str, object]:
    """Spearman rank correlation of per-case scores on the FIXED core tier,
    between two releases of the same model.

    Why this is computable when cross-tier case-matching isn't: the core
    tier's case set never changes by design, so the same `case_id`s recur at
    every release. This lets us ask a question the mean and the standard
    deviation both miss -- has the *relative difficulty ordering* of the same
    cases stayed stable, or has it scrambled? A model that improves its mean
    score while scrambling which cases it gets right is a materially
    different finding from one that improves uniformly, even though
    `compute_tier_means` alone cannot tell them apart.

    Returns rho in [-1, 1]; a low or negative rho despite an improving mean
    is the direct signature of "hard cases worsened while easy cases
    improved" (or an equivalent scrambling), not just a hypothetical.
    """
    scores_a = {r.case_id: r.score for r in results if r.model == model and r.release == release_a and r.tier == "core"}
    scores_b = {r.case_id: r.score for r in results if r.model == model and r.release == release_b and r.tier == "core"}
    shared_ids = sorted(set(scores_a) & set(scores_b))

    if len(shared_ids) < 3:
        return {
            "computable": False,
            "reason": "need >= 3 shared core case_ids across both releases",
            "n_shared_cases": len(shared_ids),
        }

    xs = [scores_a[cid] for cid in shared_ids]
    ys = [scores_b[cid] for cid in shared_ids]
    rho = _pearson_r(_rank(xs), _rank(ys))

    return {
        "computable": rho is not None,
        "release_a": release_a,
        "release_b": release_b,
        "spearman_rho": rho,
        "n_shared_cases": len(shared_ids),
    }


def core_case_rank_stability_ci(
    results: List[CaseResult],
    model: str,
    release_a: str,
    release_b: str,
    n_bootstrap: int = 1000,
    seed: Optional[int] = None,
    method: str = "bca",
    small_sample_floor: int = 6,
) -> Dict[str, object]:
    """core_case_rank_stability, with a bootstrap confidence interval around
    the point-estimate rho, rather than a bare correlation with no sense of
    how much sampling noise it carries.

    Procedure: paired bootstrap over the shared (case_a_score, case_b_score)
    pairs -- resampling PAIRS jointly (not the two releases' scores
    independently), which is what preserves the correlation structure being
    estimated. A wide interval spanning zero means the point estimate is
    not distinguishable from no rank relationship at all, given how few
    shared cases the correlation was computed over; a narrow interval far
    from zero is a robust finding.

    INTERVAL METHOD (`method`, default "bca"):

      "bca"        -- bias-corrected and accelerated. The default, because
                      this statistic sits in the exact regime where the plain
                      percentile interval is least trustworthy: rho is bounded
                      in [-1, 1], a healthy fixed core tier is SUPPOSED to sit
                      near +1, and the interval is computed over few shared
                      cases. Near the boundary the bootstrap distribution is
                      compressed and skewed, so the naive 2.5%/97.5% cut
                      points are miscalibrated -- in a direction that depends
                      on the data, NOT reliably toward a wider or a narrower
                      interval. Observed on this module's own test data: in
                      one case the naive interval understates a stable core
                      set's stability; in another it excludes zero when the
                      corrected interval does not, i.e. reports a robust rank
                      finding that isn't one. See `_bca_bounds`.
      "percentile" -- the naive interval, retained so the two can be compared
                      on the same replicates (`report()` prints exactly that
                      comparison) and so prior behaviour stays reproducible.

    Both methods are reported: `ci_low`/`ci_high` follow `method`, while
    `ci_low_percentile`/`ci_high_percentile` always carry the naive interval
    for reference, and `ci_method` records which one `ci_low`/`ci_high` and
    therefore `spans_zero` came from. When BCa is requested but undefined
    (a boundary case such as rho = +/-1, where every replicate lands on one
    side of the point estimate), this falls back to the percentile interval
    and says so in `ci_method` and `ci_method_fallback_reason` -- it does not
    silently return a differently-derived number under the same key.

    SAMPLE-SIZE HONESTY: `core_case_rank_stability` gates only at n >= 3
    shared cases, which is enough to COMPUTE a rho but nowhere near enough
    to trust an interval around it -- at n = 3-5 the jackknife skewness
    estimate BCa depends on is itself extremely noisy, and resamples
    frequently collapse to degenerate rank vectors. `small_sample_warning`
    is set whenever n < `small_sample_floor` (default 6); treat the interval
    as directional only in that regime rather than as a calibrated bound.
    """
    if method not in ("bca", "percentile"):
        return {"computable": False, "reason": "method must be 'bca' or 'percentile'"}

    point = core_case_rank_stability(results, model, release_a, release_b)
    if not point.get("computable", False):
        return point  # propagate the same not-computable reason unchanged

    scores_a = {r.case_id: r.score for r in results if r.model == model and r.release == release_a and r.tier == "core"}
    scores_b = {r.case_id: r.score for r in results if r.model == model and r.release == release_b and r.tier == "core"}
    shared_ids = sorted(set(scores_a) & set(scores_b))
    paired = [(scores_a[cid], scores_b[cid]) for cid in shared_ids]
    n = len(paired)

    rng = random.Random(seed)
    boot_rhos: List[float] = []
    for _ in range(n_bootstrap):
        sample = [paired[rng.randrange(n)] for _ in range(n)]
        xs = [s[0] for s in sample]
        ys = [s[1] for s in sample]
        rho = _pearson_r(_rank(xs), _rank(ys))
        if rho is not None:
            boot_rhos.append(rho)

    if not boot_rhos:
        return {
            **point,
            "bootstrap_computable": False,
            "reason": "all bootstrap resamples were degenerate (zero rank variance)",
        }

    boot_rhos.sort()
    pct_low = _sorted_quantile(boot_rhos, 0.025)
    pct_high = _sorted_quantile(boot_rhos, 0.975)

    ci_low, ci_high = pct_low, pct_high
    ci_method = "percentile"
    fallback_reason = None
    z0 = acceleration = None

    if method == "bca":
        # Jackknife: leave one PAIR out at a time. This is the only extra
        # cost over the percentile interval -- n statistic evaluations, no
        # additional resampling.
        jackknife: List[float] = []
        for i in range(n):
            sub = paired[:i] + paired[i + 1:]
            if len(sub) < 2:
                continue
            rho_i = _pearson_r(_rank([s[0] for s in sub]), _rank([s[1] for s in sub]))
            if rho_i is not None:
                jackknife.append(rho_i)

        bca = _bca_bounds(boot_rhos, point["spearman_rho"], jackknife, alpha=0.05)
        if bca.get("computable", False):
            ci_low, ci_high = bca["ci_low"], bca["ci_high"]
            ci_method = "bca"
            z0, acceleration = bca["z0"], bca["acceleration"]
        else:
            fallback_reason = bca["reason"]

    return {
        **point,
        "bootstrap_computable": True,
        "ci_low": ci_low,
        "ci_high": ci_high,
        "ci_method": ci_method,
        "ci_method_requested": method,
        "ci_method_fallback_reason": fallback_reason,
        "ci_low_percentile": pct_low,
        "ci_high_percentile": pct_high,
        "bca_z0": z0,
        "bca_acceleration": acceleration,
        "n_bootstrap": len(boot_rhos),
        "spans_zero": ci_low <= 0.0 <= ci_high,
        "small_sample_warning": n < small_sample_floor,
        "note": (
            "Interval method is recorded in ci_method -- BCa corrects the "
            "median-bias and skew that the naive percentile interval ignores "
            "for a bounded statistic near its boundary. Surface ci_method "
            "alongside the interval if you display it. Neither interval is a "
            "certified bound; at small n (see small_sample_warning) read it "
            "as directional only."
        ),
    }


def _ols(y: List[float], X: List[List[float]]) -> Optional[Dict[str, object]]:
    """Numerically stable ordinary least squares via ``numpy.linalg.lstsq``.

    Regression is an optional Tier-3 observation.  It deliberately has no
    hand-rolled linear-algebra fallback: silently switching from LAPACK-backed
    least squares to normal equations would change the numerical contract.
    Install ``benchmark-stewardship[stats]`` to enable it.
    """
    n = len(y)
    p = len(X[0])
    if n <= p:
        return None
    if not _HAS_NUMPY:
        raise RuntimeError(
            "adaptive_overfitting_regression requires NumPy; "
            "install benchmark-stewardship[stats]"
        )
    try:
        X_arr = _np.array(X, dtype=_np.float64)
        y_arr = _np.array(y, dtype=_np.float64)
        beta_arr, _, _, _ = _np.linalg.lstsq(X_arr, y_arr, rcond=None)
        fitted = X_arr @ beta_arr
        resid = y_arr - fitted
        ss_res = float(_np.sum(resid**2))
        dof = n - p
        sigma2 = ss_res / dof if dof > 0 else None
        return {
            "beta": [float(b) for b in beta_arr],
            "residuals": [float(r) for r in resid],
            "sigma2": sigma2,
            "dof": dof,
            "n": n,
            "p": p,
            "solver": "numpy.linalg.lstsq",
        }
    except _np.linalg.LinAlgError:
        return None

def adaptive_overfitting_regression(
    history: List[TierMeans],
    release_meta: Dict[str, ReleaseMeta],
    model_family: Dict[str, str],
    gap_name: str = "gap_core_prospective",
) -> Dict[str, object]:
    """Upgrade over `adaptive_overfitting_check`'s single correlation: a
    fixed-effects OLS regression of

        gap ~ 1 + submissions + calendar_days_since_first + family_dummies

    testing whether the submissions coefficient (beta_1) is positive after
    accounting for calendar time and model family -- separating
    submission-driven adaptive optimization from simple improvement over
    time or a strong-family effect.

    This is classical fixed-effects OLS, not a proper mixed-effects model
    with random effects per release -- that upgrade needs real statistical
    software (statsmodels / lme4) and is intentionally not attempted by hand
    here. What's implemented is the honest, smaller claim: a multiple
    regression that at least separates submissions from calendar time and
    family, rather than the bivariate correlation alone.
    """
    releases = [h.release for h in history if getattr(h, gap_name) is not None and h.release in release_meta]
    if len(releases) < 5:
        return {"computable": False, "reason": "need >= 5 releases with metadata and a computable gap"}

    first_date = min(release_meta[r].date for r in releases)
    families = sorted({model_family.get(r, "unknown") for r in releases})
    # Drop one family as the reference level to avoid the dummy-variable trap.
    family_dummies = families[1:]

    y = [getattr(next(h for h in history if h.release == r), gap_name) for r in releases]
    X = []
    for r in releases:
        meta = release_meta[r]
        calendar_days = (meta.date - first_date).days
        fam = model_family.get(r, "unknown")
        row = [1.0, float(meta.n_prior_submissions), float(calendar_days)]
        row += [1.0 if fam == f else 0.0 for f in family_dummies]
        X.append(row)

    if not _HAS_NUMPY:
        return {
            "computable": False,
            "reason": "adaptive_overfitting_regression requires NumPy",
            "required_extra": "stats",
        }
    fit = _ols(y, X)
    if fit is None:
        return {"computable": False, "reason": "insufficient degrees of freedom or collinear predictors"}

    beta = fit["beta"]
    names = ["intercept", "n_submissions", "calendar_days"] + [f"family[{f}]" for f in family_dummies]
    coefficients = dict(zip(names, beta))

    return {
        "computable": True,
        "gap_name": gap_name,
        "coefficients": coefficients,
        "beta_submissions": coefficients["n_submissions"],
        "beta_submissions_positive": coefficients["n_submissions"] > 0,
        "dof": fit["dof"],
        "n_releases": fit["n"],
        "note": (
            "One observation among several -- classical fixed-effects "
            "OLS; standard errors and significance testing are NOT computed "
            "here (too few releases in any real deployment to trust "
            "asymptotic inference). Read beta_submissions as a directional "
            "signal to corroborate against the simpler correlation in "
            "adaptive_overfitting_check, not as a hypothesis test on its own. "
            "This is a deliberately minimal-assumption design choice: a "
            "hierarchical or mixed-effects model with random intercepts per "
            "release can replace this summary as a richer observation, "
            "without changing the surveillance framework itself."
        ),
    }


def probability_discrepancy_increased(
    results: List[CaseResult],
    model: str,
    release_a: str,
    release_b: str,
    gap_name: str = "gap_core_prospective",
    n_bootstrap: int = 2000,
    seed: Optional[int] = None,
) -> Dict[str, object]:
    """A probabilistic summary, rather than only a point-estimate gap.

    Every other function in this module reports a scalar: a mean, a
    standard deviation, a correlation, a regression coefficient. Those
    answer "how big." This answers a different, often more decision-relevant
    question -- "how likely is it that the transfer discrepancy statistic
    genuinely increased from release_a to release_b" -- by case-level
    bootstrap resampling within each tier at each release, rather than
    treating the single observed Delta_t at each release as if it carried no
    sampling uncertainty of its own.

    Procedure: for each of `n_bootstrap` iterations, resample (with
    replacement) the per-case scores within core and within prospective, at
    release_a and at release_b independently, recompute Delta_t for each
    release from the resampled cases, and record whether the resampled
    Delta_t at release_b exceeds the resampled Delta_t at release_a. The
    returned probability is the fraction of iterations where it does.

    This still only touches per-case data already in `CaseResult` -- no new
    integration surface, no distributional assumptions beyond what the mean
    and standard deviation already assumed. It is a wider probabilistic
    envelope around the same point estimate `pre_post_release_gap` or
    `drift_flag` already compute, not a different underlying object.

    NOT A CANDIDATE FOR THE BCa CORRECTION applied in
    `core_case_rank_stability_ci`, deliberately: this function returns a
    TAIL PROBABILITY (the fraction of resamples in which the gap increased),
    not a confidence interval around a point estimate. BCa adjusts which
    QUANTILES of a bootstrap distribution to read an interval off; there is
    no interval here to adjust. The relevant caveat for this statistic is a
    different one -- the reported fraction is a bootstrap probability, not a
    posterior probability and not a p-value, and it inherits the usual
    small-n unreliability of the mean difference it is built on.
    """
    core_a = [r.score for r in results if r.model == model and r.release == release_a and r.tier == "core"]
    core_b = [r.score for r in results if r.model == model and r.release == release_b and r.tier == "core"]
    prosp_a = [r.score for r in results if r.model == model and r.release == release_a and r.tier == "prospective"]
    prosp_b = [r.score for r in results if r.model == model and r.release == release_b and r.tier == "prospective"]

    if gap_name != "gap_core_prospective":
        return {"computable": False, "reason": "only gap_core_prospective is supported for the bootstrap"}
    if not (core_a and core_b and prosp_a and prosp_b):
        return {"computable": False, "reason": "release_a and release_b both need observed core and prospective cases"}

    rng = random.Random(seed)
    n_increased = 0
    for _ in range(n_bootstrap):
        resampled_core_a = [rng.choice(core_a) for _ in core_a]
        resampled_prosp_a = [rng.choice(prosp_a) for _ in prosp_a]
        resampled_core_b = [rng.choice(core_b) for _ in core_b]
        resampled_prosp_b = [rng.choice(prosp_b) for _ in prosp_b]

        gap_a = mean(resampled_core_a) - mean(resampled_prosp_a)
        gap_b = mean(resampled_core_b) - mean(resampled_prosp_b)
        if gap_b > gap_a:
            n_increased += 1

    point_gap_a = mean(core_a) - mean(prosp_a)
    point_gap_b = mean(core_b) - mean(prosp_b)

    return {
        "computable": True,
        "release_a": release_a,
        "release_b": release_b,
        "point_gap_a": point_gap_a,
        "point_gap_b": point_gap_b,
        "probability_discrepancy_increased": n_increased / n_bootstrap,
        "n_bootstrap": n_bootstrap,
        "note": (
            "Case-level bootstrap over observed scores only -- not a "
            "generative model of unseen cases, and not proof of any "
            "particular cause even at high probability. One more "
            "observation, on the same footing as every other "
            "statistic in this module."
        ),
    }


def _cusum_recursion(standardized_devs: List[float], k: float) -> Dict[str, List[float]]:
    """The bare two-sided CUSUM (Page's test) recursion, operating on a
    plain list of ALREADY-STANDARDIZED deviations -- (x_t - mu0) / sigma0 --
    against a fixed baseline mu0/sigma0. Kept separate from any tier/release
    machinery so the arithmetic itself is trivial to hand-verify:

        C+_i = max(0, C+_{i-1} + dev_i - k)   -- accumulates sustained increases
        C-_i = max(0, C-_{i-1} - dev_i - k)   -- accumulates sustained decreases

    `k` (in units of sigma0) is the allowance/slack -- the size of shift the
    chart is willing to ignore per step. Standard SPC default is k=0.5,
    tuned to detect roughly a 1-sigma sustained shift efficiently (Montgomery,
    "Introduction to Statistical Quality Control").
    """
    c_plus, c_minus = [], []
    running_plus = running_minus = 0.0
    for dev in standardized_devs:
        running_plus = max(0.0, running_plus + dev - k)
        running_minus = max(0.0, running_minus - dev - k)
        c_plus.append(running_plus)
        c_minus.append(running_minus)
    return {"c_plus": c_plus, "c_minus": c_minus}



def _binomial_wilson_interval(successes: int, total: int, z: float = 1.96) -> List[float]:
    """Wilson interval for a simulated alarm probability."""
    if total <= 0:
        return [0.0, 1.0]
    p = successes / total
    denom = 1.0 + z * z / total
    centre = (p + z * z / (2.0 * total)) / denom
    half = z * math.sqrt((p * (1.0 - p) + z * z / (4.0 * total)) / total) / denom
    return [max(0.0, centre - half), min(1.0, centre + half)]


def _baseline_statistic_values(values: List[float]) -> Dict[str, Optional[float]]:
    """Compute finite-sample Phase-I diagnostic statistics.

    The returned statistics are descriptive. Their evidential meaning is
    supplied separately by null calibration in ``_baseline_diagnostics``.
    """
    n = len(values)
    mu = mean(values)
    sigma = stdev(values) if n >= 2 else 0.0
    lag1 = None
    if n >= 3:
        x, y = values[:-1], values[1:]
        mx, my = mean(x), mean(y)
        den = math.sqrt(sum((v - mx) ** 2 for v in x) * sum((v - my) ** 2 for v in y))
        lag1 = sum((a - mx) * (b - my) for a, b in zip(x, y)) / den if den else 0.0
    skew = None
    if n >= 3 and sigma > 0:
        skew = (n / ((n - 1) * (n - 2))) * sum(((v - mu) / sigma) ** 3 for v in values)
    slope = None
    trend_span_sigma = None
    if n >= 3:
        xs = list(range(n)); xm = mean(xs)
        den = sum((x - xm) ** 2 for x in xs)
        slope = sum((x - xm) * (v - mu) for x, v in zip(xs, values)) / den if den else 0.0
        if sigma > 0:
            trend_span_sigma = slope * (n - 1) / sigma
    return {
        'lag1_autocorrelation': lag1,
        'sample_skewness': skew,
        'linear_slope_per_release': slope,
        'trend_span_in_sample_sigma': trend_span_sigma,
    }


def _empirical_upper_quantile(values: List[float], probability: float) -> float:
    """Conservative nearest-rank upper quantile for a simulated null."""
    ordered = sorted(values)
    index = max(0, min(len(ordered) - 1, math.ceil(probability * len(ordered)) - 1))
    return ordered[index]


@lru_cache(maxsize=64)
def _baseline_null_distributions(
    n: int, n_simulations: int, seed: int,
) -> Dict[str, tuple]:
    """Cache scale-free finite-sample diagnostic null distributions."""
    rng = random.Random(seed)
    null_abs = {
        'lag1_autocorrelation': [],
        'sample_skewness': [],
        'trend_span_in_sample_sigma': [],
    }
    for _ in range(n_simulations):
        sample = [rng.gauss(0.0, 1.0) for _ in range(n)]
        stats = _baseline_statistic_values(sample)
        for name in null_abs:
            value = stats[name]
            if value is not None and math.isfinite(value):
                null_abs[name].append(abs(value))
    return {name: tuple(values) for name, values in null_abs.items()}


def _baseline_diagnostics(
    values: List[float], *, alpha: float = 0.01,
    n_simulations: int = 4000, seed: int = 96431,
) -> Dict[str, object]:
    """Null-calibrated advisory diagnostics for a Phase-I baseline.

    Each two-sided p-value is referenced to iid Gaussian samples of the same
    finite size. Warnings fire only when ``p <= alpha``. These are assumption
    checks, not alarms or proof that Phase I is out of control.
    """
    if not 0.0 < alpha < 1.0:
        raise ValueError('diagnostic alpha must lie strictly between 0 and 1')
    if n_simulations < 100:
        raise ValueError('diagnostic simulations must be at least 100')
    n = len(values)
    observed = _baseline_statistic_values(values)
    null_abs = _baseline_null_distributions(n, n_simulations, seed)

    p_values = {}
    thresholds = {}
    for name, simulations in null_abs.items():
        obs = observed[name]
        if obs is None or not simulations:
            p_values[name] = None
            thresholds[name] = None
            continue
        abs_obs = abs(obs)
        p_values[name] = (1 + sum(v >= abs_obs for v in simulations)) / (len(simulations) + 1)
        thresholds[name] = _empirical_upper_quantile(simulations, 1.0 - alpha)

    warnings = []
    if p_values['lag1_autocorrelation'] is not None and p_values['lag1_autocorrelation'] <= alpha:
        warnings.append(
            'null-unusual lag-1 statistic; at short Phase-I lengths this can also be '
            'produced by trend or other non-iid structure'
        )
    if p_values['sample_skewness'] is not None and p_values['sample_skewness'] <= alpha:
        warnings.append(
            'null-unusual skew statistic; this is an overlapping assumption check, '
            'not a uniquely identified distributional diagnosis'
        )
    if p_values['trend_span_in_sample_sigma'] is not None and p_values['trend_span_in_sample_sigma'] <= alpha:
        warnings.append(
            'null-unusual trend statistic; at short Phase-I lengths this can also be '
            'produced by serial dependence or other non-iid structure'
        )
    return {
        'n': n,
        **observed,
        'null_model': 'iid Gaussian samples with the same Phase-I sample size',
        'null_calibration_method': 'two-sided finite-sample Monte Carlo',
        'diagnostic_alpha': alpha,
        'n_null_simulations': n_simulations,
        'seed': seed,
        'p_values': p_values,
        'calibrated_absolute_thresholds': thresholds,
        'warnings': warnings,
        'warning_semantics': (
            'advisory, overlapping assumption checks; not monitoring alarms and not '
            'distinguishable diagnoses at short Phase-I sample sizes'
        ),
        'diagnostic_cross_talk_note': (
            'Lag-1, skew, and trend statistics are jointly noisy and can respond to the '
            'same departure from the iid Gaussian null, especially near n=12. Read a '
            'warning as evidence that the calibration assumptions merit review, not as '
            'identification of a specific failure mechanism.'
        ),
    }

def _draw_bootstrap_sample(rng: random.Random, baseline: List[float], method: str, size: int) -> List[float]:
    mu, sigma = mean(baseline), stdev(baseline)
    if method == 'empirical':
        return [rng.choice(baseline) for _ in range(size)]
    if method == 'parametric':
        return [rng.gauss(mu, sigma) for _ in range(size)]
    raise ValueError("arl_method must be 'parametric' or 'empirical'")


def _simulate_in_control_run_lengths(
    baseline_gaps: List[float], k_sigma: float, h_sigma: float, *,
    method: str, n_simulations: int, max_run_length: int, seed: int,
) -> List[int]:
    """Bootstrap Phase I and Phase II from the observed baseline."""
    if n_simulations < 1 or max_run_length < 1:
        raise ValueError('simulation count and horizon must be positive')
    rng = random.Random(seed)
    run_lengths = []
    for _ in range(n_simulations):
        phase1 = _draw_bootstrap_sample(rng, baseline_gaps, method, len(baseline_gaps))
        mu_hat = mean(phase1)
        sigma_hat = stdev(phase1) if len(phase1) >= 2 else 0.0
        # Degenerate empirical resamples can occur with short baselines. Redraw;
        # if repeated degeneracy persists, use the observed sample estimate.
        for _retry in range(10):
            if sigma_hat > 0:
                break
            phase1 = _draw_bootstrap_sample(rng, baseline_gaps, method, len(baseline_gaps))
            mu_hat, sigma_hat = mean(phase1), stdev(phase1)
        if sigma_hat <= 0:
            mu_hat, sigma_hat = mean(baseline_gaps), stdev(baseline_gaps)
        c_plus = c_minus = 0.0
        alarm_at = max_run_length + 1
        phase2 = _draw_bootstrap_sample(rng, baseline_gaps, method, max_run_length)
        for step, value in enumerate(phase2, 1):
            dev = (value - mu_hat) / sigma_hat
            c_plus = max(0.0, c_plus + dev - k_sigma)
            c_minus = max(0.0, c_minus - dev - k_sigma)
            if c_plus >= h_sigma or c_minus >= h_sigma:
                alarm_at = step
                break
        run_lengths.append(alarm_at)
    return run_lengths


def _calibrate_cusum_h_uncached(
    baseline_gaps: List[float], k_sigma: float, *, method: str,
    target_false_alarm_probability: float, monitoring_horizon: int,
    n_simulations: int, seed: int,
) -> Dict[str, object]:
    """Simulation-calibrate h to a declared finite-horizon false-alarm target."""
    if not 0 < target_false_alarm_probability < 1:
        raise ValueError('target_false_alarm_probability must be between 0 and 1')
    lo, hi = 0.5, 20.0
    for i in range(12):
        mid = (lo + hi) / 2.0
        runs = _simulate_in_control_run_lengths(
            baseline_gaps, k_sigma, mid, method=method,
            n_simulations=n_simulations, max_run_length=monitoring_horizon,
            seed=seed + i * 100003,
        )
        p_alarm = sum(r <= monitoring_horizon for r in runs) / n_simulations
        if p_alarm > target_false_alarm_probability:
            lo = mid
        else:
            hi = mid
    return {'h_sigma': hi, 'target_false_alarm_probability': target_false_alarm_probability,
            'monitoring_horizon': monitoring_horizon, 'n_simulations': n_simulations,
            'method': method, 'seed': seed, 'search_bracket': [lo, hi]}


@lru_cache(maxsize=128)
def _calibrate_parametric_cusum_h_cached(
    n_baseline: int, k_sigma: float, target_false_alarm_probability: float,
    monitoring_horizon: int, n_simulations: int, seed: int,
) -> tuple:
    """Cache pivotal parametric calibration by its true design inputs.

    Under a Gaussian location-scale model, Phase-I re-estimation followed by
    standardization makes the calibration invariant to the observed baseline's
    location and scale.  A canonical N(0,1) baseline is therefore sufficient.
    """
    canonical = [float(i) for i in range(n_baseline)]
    mu = mean(canonical)
    sigma = stdev(canonical)
    canonical = [(x - mu) / sigma for x in canonical]
    result = _calibrate_cusum_h_uncached(
        canonical, k_sigma, method='parametric',
        target_false_alarm_probability=target_false_alarm_probability,
        monitoring_horizon=monitoring_horizon,
        n_simulations=n_simulations, seed=seed,
    )
    return (result['h_sigma'], tuple(result['search_bracket']))


def _calibrate_cusum_h(
    baseline_gaps: List[float], k_sigma: float, *, method: str,
    target_false_alarm_probability: float, monitoring_horizon: int,
    n_simulations: int, seed: int,
) -> Dict[str, object]:
    """Calibrate h, caching the pivotal parametric design calculation."""
    if method == 'parametric':
        h_sigma, bracket = _calibrate_parametric_cusum_h_cached(
            len(baseline_gaps), k_sigma, target_false_alarm_probability,
            monitoring_horizon, n_simulations, seed,
        )
        return {
            'h_sigma': h_sigma,
            'target_false_alarm_probability': target_false_alarm_probability,
            'monitoring_horizon': monitoring_horizon,
            'n_simulations': n_simulations,
            'method': method,
            'seed': seed,
            'search_bracket': list(bracket),
            'calibration_basis': (
                'pivotal Gaussian location-scale calibration; depends on baseline '
                'size and design parameters, not observed baseline values'
            ),
            'cacheable': True,
        }
    result = _calibrate_cusum_h_uncached(
        baseline_gaps, k_sigma, method=method,
        target_false_alarm_probability=target_false_alarm_probability,
        monitoring_horizon=monitoring_horizon,
        n_simulations=n_simulations, seed=seed,
    )
    result['calibration_basis'] = 'observed-baseline empirical bootstrap'
    result['cacheable'] = False
    return result


def _simulate_in_control_arl(
    baseline_gaps: List[float], k_sigma: float, h_sigma: float, *,
    method: str = 'parametric', n_simulations: int = 500,
    max_run_length: int = 500, seed: int = 1729,
) -> Dict[str, object]:
    """Estimate finite-horizon in-control operating characteristics.

    The ordinary ARL is not claimed when simulations remain unalarmed. The
    primary run-length summary is therefore a restricted mean through the
    stated horizon, with censoring and Monte Carlo uncertainty surfaced.
    """
    runs = _simulate_in_control_run_lengths(
        baseline_gaps, k_sigma, h_sigma, method=method,
        n_simulations=n_simulations, max_run_length=max_run_length, seed=seed,
    )
    alarmed = [r for r in runs if r <= max_run_length]
    restricted = [min(r, max_run_length) for r in runs]
    rml = mean(restricted)
    rml_se = stdev(restricted) / math.sqrt(n_simulations) if n_simulations >= 2 else 0.0
    by20 = sum(r <= min(20, max_run_length) for r in runs)
    byh = len(alarmed)
    censored = n_simulations - byh
    return {
        'restricted_mean_run_length': rml,
        'restricted_mean_run_length_se': rml_se,
        'restricted_mean_run_length_ci': [max(0.0, rml - 1.96 * rml_se), rml + 1.96 * rml_se],
        'rml_horizon': max_run_length,
        'ordinary_arl_estimate': mean(alarmed) if censored == 0 else None,
        'arl_estimate_kind': 'complete' if censored == 0 else 'right_censored',
        'method': f'{method} bootstrap from observed Phase-I baseline with re-estimation',
        'n_simulations': n_simulations,
        'right_censored_runs': censored,
        'alarm_probability_by_20_releases': by20 / n_simulations,
        'alarm_probability_by_20_releases_ci': _binomial_wilson_interval(by20, n_simulations),
        'alarm_probability_by_horizon': byh / n_simulations,
        'alarm_probability_by_horizon_ci': _binomial_wilson_interval(byh, n_simulations),
        'seed': seed,
    }


def cusum_statistic(
    observations: List[float],
    *,
    mu0: float,
    sigma0: float,
    k_sigma: float = 0.5,
    h_sigma: float = 5.0,
) -> Dict[str, object]:
    """Bare two-sided CUSUM with caller-supplied design parameters.

    This is the compact, deterministic Layer-1 statistic.  It performs no
    baseline estimation, simulation calibration, diagnostics, or operating-
    characteristic estimation.  ``cusum_monitor`` is the calibrated extension.
    """
    if sigma0 <= 0 or not math.isfinite(sigma0):
        raise ValueError("sigma0 must be finite and positive")
    if not math.isfinite(mu0):
        raise ValueError("mu0 must be finite")
    if k_sigma < 0 or not math.isfinite(k_sigma):
        raise ValueError("k_sigma must be finite and non-negative")
    if h_sigma <= 0 or not math.isfinite(h_sigma):
        raise ValueError("h_sigma must be finite and positive")
    if any(not math.isfinite(x) for x in observations):
        raise ValueError("observations must all be finite")
    standardized = [(x - mu0) / sigma0 for x in observations]
    recursion = _cusum_recursion(standardized, k_sigma)
    first_alarm_index = first_alarm_direction = None
    for i, (cp, cm) in enumerate(zip(recursion["c_plus"], recursion["c_minus"])):
        if cp >= h_sigma:
            first_alarm_index, first_alarm_direction = i, "increase"
            break
        if cm >= h_sigma:
            first_alarm_index, first_alarm_direction = i, "decrease"
            break
    return {
        "mu0": mu0, "sigma0": sigma0, "k_sigma": k_sigma, "h_sigma": h_sigma,
        "standardized_deviations": standardized,
        "c_plus": recursion["c_plus"], "c_minus": recursion["c_minus"],
        "alarmed": first_alarm_index is not None,
        "first_alarm_index": first_alarm_index,
        "first_alarm_direction": first_alarm_direction,
        "estimate_kind": "deterministic_statistic",
    }


def cusum_monitor(
    history: List[TierMeans], gap_name: str = 'gap_core_prospective',
    n_baseline: int = 12, k_sigma: float = 0.5, h_sigma: Optional[float] = None,
    *, target_false_alarm_probability: float = 0.05,
    calibration_horizon: int = 20, arl_method: str = 'parametric',
    arl_simulations: int = 500, arl_horizon: int = 500,
    arl_seed: int = 1729, estimate_in_control_arl: bool = True,
    diagnostic_alpha: float = 0.01, diagnostic_simulations: int = 4000,
    diagnostic_seed: int = 96431,
) -> Dict[str, object]:
    """Two-sided CUSUM with observed-baseline calibration and auditable OC output.

    When ``h_sigma`` is omitted, the limit is simulation-calibrated against
    the observed Phase-I baseline to the declared finite-horizon false-alarm
    target. The returned run-length summary is a restricted mean whenever
    simulations are right-censored; it is not mislabeled as an ordinary ARL.
    """
    if n_baseline < 3:
        raise ValueError('n_baseline must be at least 3')
    if k_sigma < 0:
        raise ValueError('k_sigma must be non-negative')
    if arl_method not in {'parametric', 'empirical'}:
        raise ValueError("arl_method must be 'parametric' or 'empirical'")
    valid = [(h.release, getattr(h, gap_name)) for h in history if getattr(h, gap_name) is not None]
    if len(valid) < n_baseline + 1:
        return {'computable': False, 'reason': f'need >= {n_baseline + 1} releases with a computable gap ({n_baseline} baseline + at least 1 monitored)'}
    baseline_releases, monitoring_releases = valid[:n_baseline], valid[n_baseline:]
    baseline_gaps = [g for _, g in baseline_releases]
    mu0, sigma0 = mean(baseline_gaps), stdev(baseline_gaps)
    if sigma0 == 0:
        return {'computable': False, 'reason': 'baseline has zero variance -- cannot standardize deviations', 'mu0': mu0}

    requested_h_sigma = h_sigma
    calibration = None
    if h_sigma is None:
        calibration = _calibrate_cusum_h(
            baseline_gaps, k_sigma, method=arl_method,
            target_false_alarm_probability=target_false_alarm_probability,
            monitoring_horizon=calibration_horizon,
            n_simulations=max(200, arl_simulations), seed=arl_seed,
        )
        effective_h_sigma = calibration['h_sigma']
    else:
        effective_h_sigma = h_sigma
    if effective_h_sigma <= 0:
        raise ValueError('h_sigma must be positive')

    standardized = [(g - mu0) / sigma0 for _, g in monitoring_releases]
    cusum = _cusum_recursion(standardized, k_sigma)
    first_alarm_release = first_alarm_direction = None
    for (release, _), cp, cm in zip(monitoring_releases, cusum['c_plus'], cusum['c_minus']):
        if cp >= effective_h_sigma:
            first_alarm_release, first_alarm_direction = release, 'increase'; break
        if cm >= effective_h_sigma:
            first_alarm_release, first_alarm_direction = release, 'decrease'; break
    trace = [{'release': release, 'gap': gap, 'standardized_deviation': dev,
              'c_plus': cp, 'c_minus': cm}
             for (release, gap), dev, cp, cm in zip(monitoring_releases, standardized, cusum['c_plus'], cusum['c_minus'])]
    oc = None
    if estimate_in_control_arl and arl_simulations > 0:
        oc = _simulate_in_control_arl(
            baseline_gaps, k_sigma, effective_h_sigma, method=arl_method,
            n_simulations=arl_simulations, max_run_length=arl_horizon, seed=arl_seed + 7919,
        )
    return {
        'computable': True, 'gap_name': gap_name, 'n_baseline': n_baseline,
        'mu0': mu0, 'sigma0': sigma0, 'k_sigma': k_sigma,
        'h_sigma': effective_h_sigma, 'requested_h_sigma': requested_h_sigma,
        'h_sigma_calibrated_from_observed_baseline': requested_h_sigma is None,
        'calibration': calibration, 'baseline_diagnostics': _baseline_diagnostics(
            baseline_gaps, alpha=diagnostic_alpha,
            n_simulations=diagnostic_simulations, seed=diagnostic_seed,
        ),
        'in_control_operating_characteristics': oc,
        'restricted_mean_in_control_run_length': None if oc is None else oc['restricted_mean_run_length'],
        'trace': trace, 'alarmed': first_alarm_release is not None,
        'first_alarm_release': first_alarm_release, 'first_alarm_direction': first_alarm_direction,
    }

def cusum_change_point_bootstrap(
    results: List[CaseResult],
    model: str,
    releases_in_order: List[str],
    n_baseline: int = 12,
    k_sigma: float = 0.5,
    h_sigma: Optional[float] = None,
    n_bootstrap: int = 500,
    seed: Optional[int] = None,
) -> Dict[str, object]:
    """Case-level bootstrap uncertainty around cusum_monitor's change-point
    estimate: not just "alarmed=True" but a range of releases the change
    point plausibly falls in given resampling noise in the observed cases.

    `cusum_monitor` reports a single point estimate for the first alarming
    release, computed once from the observed per-tier means. This function
    resamples (with replacement) the per-case core and prospective scores
    at EVERY release, recomputes Delta_t and reruns the full CUSUM procedure
    on each resampled draw, and reports where the change point falls across
    those draws -- an estimate, an uncertainty interval, and how often no
    alarm fires at all, rather than a single flag with no sense of how
    borderline or robust it is.

    Requires per-case scores (the same CaseResult records already used
    elsewhere), not just the aggregated TierMeans history -- this is why it
    takes `results` directly rather than a `List[TierMeans]`.

    NOT A CANDIDATE FOR THE BCa CORRECTION applied in
    `core_case_rank_stability_ci`, deliberately: the quantity being
    intervalled here is a DISCRETE ORDINAL INDEX (which release in
    `monitoring_releases` alarmed first), not a continuous statistic. BCa's
    acceleration term is a jackknife estimate of how the standard error
    changes with the parameter, which is not meaningful for an index taking
    a handful of tied integer values, and its adjusted quantiles would be
    read back onto the same coarse grid regardless. The percentile interval
    over alarm indices stays, and should be read as "the alarm landed in
    this span of releases across resamples," not as a calibrated interval.
    Note also that `bootstrap_fraction_alarmed` conditions the interval:
    releases where no alarm fired are excluded from the span entirely, so a
    low fraction_alarmed makes a narrow-looking span misleading -- always
    read the two together.
    """
    core_by_release: Dict[str, List[float]] = {}
    prosp_by_release: Dict[str, List[float]] = {}
    for rel in releases_in_order:
        core_by_release[rel] = [r.score for r in results if r.model == model and r.release == rel and r.tier == "core"]
        prosp_by_release[rel] = [r.score for r in results if r.model == model and r.release == rel and r.tier == "prospective"]
        if not core_by_release[rel] or not prosp_by_release[rel]:
            return {"computable": False, "reason": f"release {rel!r} is missing core or prospective cases"}

    if len(releases_in_order) < n_baseline + 1:
        return {"computable": False, "reason": f"need >= {n_baseline + 1} releases"}

    monitoring_releases = releases_in_order[n_baseline:]

    # Point estimate gaps establish the observed Phase-I calibration sample.
    original_gaps = [mean(core_by_release[r]) - mean(prosp_by_release[r]) for r in releases_in_order]
    if h_sigma is None:
        effective_h_sigma = _calibrate_cusum_h(
            original_gaps[:n_baseline], k_sigma, method="parametric",
            target_false_alarm_probability=0.05, monitoring_horizon=20,
            n_simulations=300, seed=1729,
        )["h_sigma"]
    else:
        effective_h_sigma = h_sigma

    def _run_cusum(gaps: List[float]) -> Optional[int]:
        """Returns the 0-based index into monitoring_releases of the first
        alarm, or None if it never alarms. Returns None also if the
        baseline is degenerate (zero variance)."""
        baseline = gaps[:n_baseline]
        mu0 = mean(baseline)
        sigma0 = stdev(baseline) if len(baseline) >= 2 else 0.0
        if sigma0 == 0:
            return None
        standardized = [(g - mu0) / sigma0 for g in gaps[n_baseline:]]
        cusum = _cusum_recursion(standardized, k_sigma)
        for i, (cp, cm) in enumerate(zip(cusum["c_plus"], cusum["c_minus"])):
            if cp >= effective_h_sigma or cm >= effective_h_sigma:
                return i
        return None

    # Point estimate from the observed (unresampled) data.
    point_alarm_index = _run_cusum(original_gaps)
    point_alarm_release = monitoring_releases[point_alarm_index] if point_alarm_index is not None else None

    rng = random.Random(seed)
    alarm_indices: List[Optional[int]] = []
    for _ in range(n_bootstrap):
        resampled_gaps = []
        for rel in releases_in_order:
            c, p = core_by_release[rel], prosp_by_release[rel]
            resampled_core = [rng.choice(c) for _ in c]
            resampled_prosp = [rng.choice(p) for _ in p]
            resampled_gaps.append(mean(resampled_core) - mean(resampled_prosp))
        alarm_indices.append(_run_cusum(resampled_gaps))

    n_alarmed = sum(1 for a in alarm_indices if a is not None)
    fraction_alarmed = n_alarmed / n_bootstrap
    alarmed_indices = sorted(a for a in alarm_indices if a is not None)

    if alarmed_indices:
        lo = alarmed_indices[int(0.025 * len(alarmed_indices))]
        hi = alarmed_indices[min(len(alarmed_indices) - 1, int(0.975 * len(alarmed_indices)))]
        ci_low_release, ci_high_release = monitoring_releases[lo], monitoring_releases[hi]
    else:
        ci_low_release = ci_high_release = None

    return {
        "computable": True,
        "point_estimate_alarm_release": point_alarm_release,
        "bootstrap_fraction_alarmed": fraction_alarmed,
        "bootstrap_ci_release_low": ci_low_release,
        "bootstrap_ci_release_high": ci_high_release,
        "n_bootstrap": n_bootstrap,
        "note": (
            "Case-level bootstrap over observed scores only. The interval "
            "describes variability in WHERE the change point falls given "
            "resampling noise already present in the observed cases -- not "
            "a generative model of unseen cases, and a low "
            "bootstrap_fraction_alarmed is itself informative: it means the "
            "point-estimate alarm is not robust to resampling."
        ),
    }


def z_to_two_sided_pvalue(z: float) -> float:
    """Two-sided normal-approximation p-value for a z-score, via the
    complementary error function (math.erfc, standard library -- no
    scipy/numpy dependency): p = erfc(|z| / sqrt(2)).
    """
    return math.erfc(abs(z) / math.sqrt(2))


def benjamini_hochberg(p_values: List[float], alpha: float = 0.05) -> Dict[str, object]:
    """Benjamini-Hochberg false-discovery-rate correction across MULTIPLE
    simultaneous surveillance tests -- e.g. drift_flag or cusum_monitor
    z-scores computed across many models/releases at once, not a single
    model in isolation.

    Why this matters here specifically: this module can run up to seven
    roughly-independent statistics per release, and a real deployment would
    run any one of them across dozens of models. Concordance across
    independent statistics is offered elsewhere in this module as evidence
    for a genuine change in measurement fitness -- but run enough statistics
    across enough models, and apparent concordance will occur by chance at a nontrivial rate if
    nothing corrects for how many chances it had to occur. NOHARM's own
    paper applies exactly this correction for the same reason (Benjamini-
    Hochberg FDR across 33 models x 3 metrics = 99 comparisons).

    Standard step-up BH procedure: sort p-values ascending; find the largest
    rank k such that p_(k) <= (k/m)*alpha; reject (mark significant) every
    hypothesis at rank <= k. Returns significance flags and BH-adjusted
    p-values (q-values) in the SAME order as the input list, not sorted.
    """
    m = len(p_values)
    if m == 0:
        return {"computable": False, "reason": "no p-values supplied"}

    order = sorted(range(m), key=lambda i: p_values[i])
    sorted_p = [p_values[i] for i in order]

    largest_k = 0
    for k in range(1, m + 1):
        if sorted_p[k - 1] <= (k / m) * alpha:
            largest_k = k

    significant_sorted = [(i + 1) <= largest_k for i in range(m)]

    raw_q = [(m / (i + 1)) * sorted_p[i] for i in range(m)]
    q_sorted = [0.0] * m
    running_min = 1.0
    for i in range(m - 1, -1, -1):
        running_min = min(running_min, raw_q[i])
        q_sorted[i] = min(running_min, 1.0)

    significant = [False] * m
    q_values = [0.0] * m
    for pos, orig_i in enumerate(order):
        significant[orig_i] = significant_sorted[pos]
        q_values[orig_i] = q_sorted[pos]

    return {
        "computable": True,
        "m": m,
        "alpha": alpha,
        "n_significant": sum(significant),
        "significant": significant,
        "q_values": q_values,
        "largest_significant_rank": largest_k,
    }


# ---------------------------------------------------------------------------
# RECOMMENDED DEPLOYMENT: a Tier-0-default entry point requiring no user
# decisions, and evidence profiles that interpret RELATIONSHIPS between
# statistics rather than combining them into a score.
# ---------------------------------------------------------------------------

class BenchmarkMonitor:
    """The recommended default entry point. Call `.update(case_results,
    release)` once per release as it arrives; internally runs Tier 0
    (cusum_monitor) against the accumulated history. No user decisions
    required for the default path -- k_sigma/h_sigma/n_baseline have
    standard defaults, and `.update()` returns the same dict `cusum_monitor`
    always has.

    This does not replace calling the individual functions directly for
    Tier 1-4 analysis; it exists so that Tier 0 -- the zero-activation-cost,
    recommended-default lever -- requires no assembly of History/TierMeans
    objects by hand. Every benchmark release should be able to call
    `monitor.update(...)` and get a CUSUM read with no further decisions.
    """

    def __init__(
        self,
        model: str,
        n_baseline: int = 12,
        k_sigma: float = 0.5,
        h_sigma: Optional[float] = None,
        gap_name: str = "gap_core_prospective",
    ):
        self.model = model
        self.n_baseline = n_baseline
        self.k_sigma = k_sigma
        self.h_sigma = h_sigma
        self.gap_name = gap_name
        self._results: List[CaseResult] = []
        self._history: List[TierMeans] = []

    def update(self, case_results: List[CaseResult], release: str) -> Dict[str, object]:
        """Add one release's CaseResult records, recompute tier means,
        append to history, and run the default Tier 0 check. Returns
        cusum_monitor's result for the history accumulated so far --
        "insufficient history" until n_baseline + 1 releases exist, exactly
        as calling cusum_monitor directly would.
        """
        self._results.extend(case_results)
        self._history.append(compute_tier_means(self._results, self.model, release))
        return cusum_monitor(
            self._history, gap_name=self.gap_name, n_baseline=self.n_baseline,
            k_sigma=self.k_sigma, h_sigma=self.h_sigma,
        )

    @property
    def history(self) -> List[TierMeans]:
        return list(self._history)

    @property
    def results(self) -> List[CaseResult]:
        """Raw per-case records accumulated so far -- needed by any Tier 1+
        function (rank stability, bootstrap CIs) a caller chooses to run
        alongside the Tier 0 default."""
        return list(self._results)


